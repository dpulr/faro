import AppKit
import CryptoKit

struct ClipEntry: Codable, Identifiable, Hashable {
    enum Kind: String, Codable { case text, image }

    var id = UUID()
    var kind: Kind
    var text = ""
    var imageFile: String?
    var width = 0
    var height = 0
    var date: Date
    var pinned = false
    var app: String?
    var hash: String

    var preview: String {
        text.prefix(240).split(whereSeparator: \.isNewline).joined(separator: " ")
            .trimmingCharacters(in: .whitespaces)
    }
}

struct ClipSettings: Codable, Equatable {
    /// 0 = sin límite.
    var retentionDays = 7
    var maxItems = 300
    var saveImages = true
    var autoPaste = true
    var paused = false
    /// Prefijos de bundle ID cuyas copias no se guardan (gestores de contraseñas).
    var excludedBundles = ["com.1password", "com.agilebits", "com.bitwarden", "com.apple.keychainaccess",
                           "com.apple.Passwords", "org.keepassxc", "com.lastpass", "com.dashlane"]

    init() {}

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let d = ClipSettings()
        retentionDays = try c.decodeIfPresent(Int.self, forKey: .retentionDays) ?? d.retentionDays
        maxItems = try c.decodeIfPresent(Int.self, forKey: .maxItems) ?? d.maxItems
        saveImages = try c.decodeIfPresent(Bool.self, forKey: .saveImages) ?? d.saveImages
        autoPaste = try c.decodeIfPresent(Bool.self, forKey: .autoPaste) ?? d.autoPaste
        paused = try c.decodeIfPresent(Bool.self, forKey: .paused) ?? d.paused
        excludedBundles = try c.decodeIfPresent([String].self, forKey: .excludedBundles) ?? d.excludedBundles
    }
}

private struct ClipFile: Codable {
    var entries: [ClipEntry]
    var settings: ClipSettings
}

/// Historial del portapapeles: vigila el cambio, guarda texto e imágenes y se limpia solo.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var entries: [ClipEntry] = []   // el más reciente primero
    @Published var settings = ClipSettings() {
        didSet { if settings != oldValue { prune(); scheduleSave() } }
    }

    private let persistent: Bool
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var saveTask: Task<Void, Never>?
    private var thumbnails: [String: NSImage] = [:]

    /// Tipos que usan los gestores de contraseñas para marcar copias que no deben guardarse.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "net.antelle.keeweb.concealed",
    ]

    static let imagesDir: URL = {
        let url = Paths.support.appendingPathComponent("clips", isDirectory: true)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }()

    private static var file: URL { Paths.support.appendingPathComponent("clipboard.json") }

    init(persistent: Bool = true) {
        self.persistent = persistent
        guard persistent else { return }
        load()
        prune()
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer?.tolerance = 0.2
        ClipboardPanelController.shared.install(store: self)
    }

    // MARK: Lectura

    var ordered: [ClipEntry] { entries.filter(\.pinned) + entries.filter { !$0.pinned } }

    func search(_ query: String) -> [ClipEntry] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return ordered }
        return ordered.filter { e in
            e.kind == .text ? e.text.localizedCaseInsensitiveContains(q)
                : "imagen captura foto".localizedCaseInsensitiveContains(q)
        }
    }

    func image(for entry: ClipEntry) -> NSImage? {
        guard let name = entry.imageFile else { return nil }
        if let cached = thumbnails[name] { return cached }
        let img = Imaging.thumbnail(of: Self.imagesDir.appendingPathComponent(name), maxPixel: 160)
        if let img { thumbnails[name] = img }
        return img
    }

    // MARK: Monitor

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !settings.paused else { return }
        if let types = pb.types, !Set(types.map(\.rawValue)).isDisjoint(with: Self.privateTypes) { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, settings.excludedBundles.contains(where: { id.hasPrefix($0) }) { return }
        let app = front?.localizedName

        if let text = pb.string(forType: .string) {
            add(text: text, app: app)
        } else if settings.saveImages, let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            add(imageData: data, app: app)
        }
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private func add(text: String, app: String?) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let clipped = String(text.prefix(200_000))
        insert(ClipEntry(kind: .text, text: clipped, date: Date(), app: app, hash: Self.hash(Data(clipped.utf8))))
    }

    private func add(imageData: Data, app: String?) {
        guard let rep = NSBitmapImageRep(data: imageData),
              let png = rep.representation(using: .png, properties: [:]), png.count < 25_000_000 else { return }
        let h = Self.hash(png)
        if let existing = entries.first(where: { $0.hash == h }) { bump(existing.id); return }
        let name = "\(UUID().uuidString).png"
        guard (try? png.write(to: Self.imagesDir.appendingPathComponent(name))) != nil else { return }
        insert(ClipEntry(kind: .image, imageFile: name, width: rep.pixelsWide, height: rep.pixelsHigh,
                         date: Date(), app: app, hash: h))
    }

    func addDemo(text: String, app: String, pinned: Bool = false, ago: TimeInterval = 0) {
        var e = ClipEntry(kind: .text, text: text, date: Date().addingTimeInterval(-ago), app: app,
                          hash: Self.hash(Data(text.utf8)))
        e.pinned = pinned
        entries.append(e)
    }

    private func insert(_ entry: ClipEntry) {
        if let index = entries.firstIndex(where: { $0.hash == entry.hash }) {
            bump(entries[index].id)
        } else {
            entries.insert(entry, at: 0)
            prune()
            scheduleSave()
        }
    }

    private func bump(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        var entry = entries.remove(at: index)
        entry.date = Date()
        entries.insert(entry, at: 0)
        scheduleSave()
    }

    // MARK: Acciones

    func copyBack(_ entry: ClipEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch entry.kind {
        case .text:
            pb.setString(entry.text, forType: .string)
        case .image:
            if let name = entry.imageFile, let img = NSImage(contentsOf: Self.imagesDir.appendingPathComponent(name)) {
                pb.writeObjects([img])
            }
        }
        lastChange = pb.changeCount // para que el monitor no lo cuente como una copia nueva
        bump(entry.id)
    }

    func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].pinned.toggle()
        scheduleSave()
    }

    func delete(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        remove(entries.remove(at: index))
        scheduleSave()
    }

    func clear(keepPinned: Bool) {
        let doomed = entries.filter { !keepPinned || !$0.pinned }
        entries.removeAll { e in doomed.contains { $0.id == e.id } }
        doomed.forEach(remove)
        scheduleSave()
    }

    private func remove(_ entry: ClipEntry) {
        guard let name = entry.imageFile else { return }
        thumbnails[name] = nil
        try? FileManager.default.removeItem(at: Self.imagesDir.appendingPathComponent(name))
    }

    /// Quita lo vencido y lo que sobra del tope; los fijados nunca se tocan.
    private func prune() {
        var doomed: [ClipEntry] = []
        if settings.retentionDays > 0 {
            let cutoff = Date().addingTimeInterval(-Double(settings.retentionDays) * 86_400)
            doomed += entries.filter { !$0.pinned && $0.date < cutoff }
        }
        let alive = entries.filter { e in !e.pinned && !doomed.contains { $0.id == e.id } }
        if alive.count > settings.maxItems { doomed += alive.suffix(alive.count - settings.maxItems) }
        guard !doomed.isEmpty else { return }
        entries.removeAll { e in doomed.contains { $0.id == e.id } }
        doomed.forEach(remove)
    }

    // MARK: Disco

    private func load() {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        guard let data = try? Data(contentsOf: Self.file),
              let stored = try? decoder.decode(ClipFile.self, from: data) else { return }
        entries = stored.entries
        settings = stored.settings
    }

    private func scheduleSave() {
        guard persistent else { return }
        saveTask?.cancel()
        saveTask = Task {
            try? await Task.sleep(nanoseconds: 800_000_000)
            guard !Task.isCancelled else { return }
            let encoder = JSONEncoder()
            encoder.dateEncodingStrategy = .iso8601
            if let data = try? encoder.encode(ClipFile(entries: entries, settings: settings)) {
                try? data.write(to: Self.file, options: .atomic)
            }
        }
    }
}
